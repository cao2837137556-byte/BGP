def main() -> None:
    args = parse_args()
    warnings: list[str] = []

    base = load_incident_base(args, warnings)
    incident_lookup, pair_lookup = load_rpki_lookup(args.rpki_lookup_file, warnings)
    component = component_audit(args, base, pair_lookup, warnings)

    table = base.merge(incident_lookup, on="incident_id", how="left")
    table = table.merge(component.drop(columns=["member_count"], errors="ignore"), on="incident_id", how="left")

    table["dominant_pair_rpki_status"] = table["dominant_pair_rpki_status"].fillna("unavailable")
    table["dominant_pair_rpki_evidence_state"] = table["dominant_pair_rpki_evidence_state"].fillna("unavailable")
    table["dominant_pair_target_id"] = table["dominant_pair_target_id"].fillna("")

    numeric_defaults = [
        "rpki_valid_member_count",
        "rpki_invalid_asn_member_count",
        "rpki_invalid_length_member_count",
        "rpki_unknown_member_count",
        "rpki_unavailable_member_count",
        "rpki_invalid_total_count",
        "rpki_valid_share",
        "rpki_invalid_share",
        "rpki_unknown_share",
        "rpki_unavailable_share",
        "dominant_prefix_origin_share",
        "rpki_status_entropy",
        "invalid_core_share",
        "invalid_edge_share",
        "suspicious_component_member_count",
        "suspicious_component_share",
    ]
    for col in numeric_defaults:
        if col not in table.columns:
            table[col] = 0
        table[col] = table[col].fillna(0)
    for col in ["mixed_rpki_status_flag", "should_split_incident_flag"]:
        if col not in table.columns:
            table[col] = False
        table[col] = table[col].fillna(False).astype(bool)
    if "component_purity_class" not in table.columns:
        table["component_purity_class"] = "insufficient_component_signal"

    if "high_share" not in table.columns:
        denominator = table["member_count"].where(table["member_count"] > 0, 1)
        table["high_share"] = table["high_count"] / denominator

    table = apply_verdicts(table)
    write_outputs(args, table, warnings)

    summary_path = Path(args.output_dir) / "r2b_vrp_verifier_summary.json"
    print(summary_path)


if __name__ == "__main__":
    main()
